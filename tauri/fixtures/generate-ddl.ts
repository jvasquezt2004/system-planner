const all = Object.values(pool).flat();
const dataStatements = new Set(pool.data);

function choose<T>(rng: Rng, items: readonly T[]): T {
	return items[Math.floor(rng() * items.length)]!;
}

function randomScript(rng: Rng): string {
	const parts: string[] = [];
	const creates = 1 + Math.floor(rng() * 3);
	for (let index = 0; index < creates; index += 1) parts.push(choose(rng, pool.create));
	if (rng() < 0.3) parts.unshift(pool.enums[0]!);
	const others = Math.floor(rng() * 5);
	for (let index = 0; index < others; index += 1) {
		const statement = choose(rng, all.filter((candidate) => !dataStatements.has(candidate) || rng() < 0.03));
		parts.push(statement);
	}
	return parts.join(rng() < 0.2 ? "\n\n" : " ");
}

const translateCases: Array<{ sql: string; out: Outcome }> = [];
const seen = new Set<string>();
let skippedBugs = 0;

async function addTranslate(sql: string) {
	if (seen.has(sql)) return;
	seen.add(sql);
	const out = await translate(sql, "n");
	if (reachesFixedBug(sql, out)) {
		skippedBugs += 1;
		return;
	}
	translateCases.push({ sql, out });
}

