// The schema files of real, mutated Designs: what apply_schema reads back most often.
const designCases = JSON.parse(readFileSync(join(dataDir, "designs.json"), "utf8")) as Array<{ name: string; result: { ok?: Design } }>;
const normalized = (name: string) => designCases.find((entry) => entry.name === name)!.result.ok!;
