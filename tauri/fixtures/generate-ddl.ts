const schemaFiles: Array<{ design: Design; sql: string }> = [];
bases.forEach((base, baseIndex) => {
	const mutator = new DesignMutator(seededRng(0xdd1 + baseIndex * 31));
	for (let index = 0; index <= 220; index += 1) {
		const doc = structuredClone(base);
		const count = index === 0 ? 0 : 1 + Math.floor(mutator.rng() * (index % 6 === 0 ? 4 : 2));
		for (let step = 0; step < count; step += 1) mutator.mutate(doc as never);
		let generated;
		try { generated = generateDesignSql(doc); } catch { continue; }
		if (!generated.ok) continue;
		schemaFiles.push({ design: doc, sql: renderSchemaFile(doc) });
	}
});
for (const entry of schemaFiles) await addTranslate(entry.sql);

// Adoption: a current Design, a script, and the identity the translation inherits.
const adoptCases: Array<{ current: Design; sql: string; out: Outcome }> = [];
let skippedPlanning = 0;
async function addAdopt(current: Design, sql: string) {
	try { planSchemaObjectNames(current); } catch { skippedPlanning += 1; return; }
	const translated = await translate(sql, "n");
	if (reachesFixedBug(sql, translated)) { skippedBugs += 1; return; }
	if ("error" in translated) { adoptCases.push({ current, sql, out: translated }); return; }
	const adopted = adoptIdentities(current, translated.design);
	const design = JSON.parse(JSON.stringify(adopted)) as Design;
	adoptCases.push({ current, sql, out: { design, kept: translated.kept, count: translated.count } });
}

/** A Design a user has worked on: moved tables, notes, and stored names removed from some indexes. */
function lived(design: Design, rng: Rng): Design {
	const copy = JSON.parse(JSON.stringify(design)) as Design;
	copy.viewport = { x: Math.floor(rng() * 100), y: Math.floor(rng() * 100), zoom: 1.5 };
	for (const table of copy.tables) {
		table.position = { x: Math.floor(rng() * 1000), y: Math.floor(rng() * 1000) };
		for (const column of table.columns) if (rng() < 0.4) column.notes = `note ${Math.floor(rng() * 100)}`;
		for (const index of table.indexes ?? []) if (rng() < 0.5) delete index.name;
		for (const constraint of table.uniqueConstraints ?? []) if (rng() < 0.5) delete constraint.name;
	}
	return copy;
}

const adoptRng = seededRng(0xad0975);
for (let index = 0; index < 700; index += 1) {
	const baseScript = randomScript(adoptRng);
	const base = await translate(baseScript, "c");
	if ("error" in base || reachesFixedBug(baseScript, base)) continue;
	const current = lived(base.design, adoptRng);
	let generated;
	try { generated = generateDesignSql(current); } catch { generated = { ok: false } as never; }
	const roll = adoptRng();
	if (roll < 0.25 && generated.ok) await addAdopt(current, renderSchemaFile(current));
	else if (roll < 0.5 && generated.ok) await addAdopt(current, `${renderSchemaFile(current)}\n${choose(adoptRng, all)}`);
	else if (roll < 0.7) await addAdopt(current, randomScript(adoptRng));
	else await addAdopt(current, baseScript.replace(/ varchar\(\d+\)/g, " text").replace(/create table (t\d+)/, "create table $1_renamed"));
}
for (const entry of schemaFiles.slice(0, 120)) {
	const current = lived(entry.design, adoptRng);
	if (!generateDesignSql(current).ok) continue;
	await addAdopt(current, renderSchemaFile(current));
	const [first] = current.tables;
	if (first) {
		const edited = renderSchemaFile(current).replace(new RegExp(`CREATE TABLE "?${first.name}"?`, "i"), `CREATE TABLE "${first.name}_x"`);
		await addAdopt(current, edited);
	}
}

const errors = translateCases.filter((entry) => "error" in entry.out).length;
const rawKept = translateCases.filter((entry) => "kept" in entry.out && entry.out.kept.length > 0).length;
const withTables = translateCases.filter((entry) => "design" in entry.out && entry.out.design.tables.length > 0).length;
console.log(`ddl: ${translateCases.length} translations (${withTables} with tables, ${rawKept} keep raw SQL, ${errors} errors), ${adoptCases.length} adoptions; left out ${skippedBugs} (fixed bugs), ${skippedPlanning} (unplannable)`);

mkdirSync(dataDir, { recursive: true });
writeFileSync(join(dataDir, "ddl.json"), `${JSON.stringify({ viewport, translate: translateCases, adopt: adoptCases })}\n`);
