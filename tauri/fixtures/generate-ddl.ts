/**
 * Differential fixtures for reading PostgreSQL DDL into a Design (`assistant-ddl.ts`) and for keeping
 * identity across a file edit (`schema-identity.ts`).
 *
 * `translate` cases: a script and what `translateDdlText` makes of it (the Design with fixed ids, the
 * statements kept as raw SQL, the statement count) or the error it throws.
 * `adopt` cases: a current Design, a script, and the Design `adoptIdentities` gives the translation.
 *
 * Scripts are hand-written statements of every kind (including the ones the Design cannot model and
 * the ones that are refused), combined at random, plus the schema files of mutated real Designs.
 *
 * Four behaviours of the original are bugs the Rust port fixes instead of copying (see ddl.rs);
 * scripts that reach them are left out so the rest is compared exactly:
 *   - `DEFAULT 0` / `DEFAULT false` are stored as the text "[object Object]",
 *   - `numeric(p, 0)` keeps the whole table as raw SQL,
 *   - a Function with parameters is kept as raw SQL,
 *   - a column's COLLATE is dropped without a trace (the code looks for `coll_clause`; the parser says `collClause`).
 *
 * Run from tauri/: bun fixtures/generate-ddl.ts
 */
