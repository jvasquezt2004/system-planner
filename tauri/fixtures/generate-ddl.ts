const empty = (): Design => ({ tables: [], relationships: [], manyToManyRelationships: [], viewport: { ...viewport } });

const counter = (prefix: string) => {
	let n = 0;
	return () => `${prefix}${++n}`;
};

type Outcome = { design: Design; kept: string[]; count: number } | { error: string };

async function translate(sql: string, prefix: string): Promise<Outcome> {
	try {
		const result = await translateDdlText(empty(), sql, counter(prefix));
		const design = JSON.parse(JSON.stringify(result.design)) as Design;
		for (const table of design.tables) {
			table.rowLevelSecurity ??= false;
			table.policies ??= [];
		}
		return { design, kept: result.keptAsSql, count: result.statementCount };
	} catch (error) {
		return { error: error instanceof Error ? error.message : String(error) };
	}
}

/** A script reaches a behaviour the Rust port deliberately fixes. */
function reachesFixedBug(sql: string, outcome: Outcome): boolean {
	if (JSON.stringify(outcome).includes("[object Object]")) return true;
	if (/numeric\s*\(\s*\d+\s*,\s*0\s*\)/i.test(sql) || /decimal\s*\(\s*\d+\s*,\s*0\s*\)/i.test(sql)) return true;
	if (/function\s+[\w."]+\s*\(\s*[^)\s]/i.test(sql)) return true;
	if (/\bcollate\b/i.test(sql)) return true;
	return false;
}

